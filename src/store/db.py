"""Transactional snapshots, content changes, and per-attempt history."""
import json
import sqlite3
from contextlib import contextmanager
from datetime import datetime, timezone

try:
    import psycopg
    from psycopg.rows import dict_row
except ImportError:
    psycopg = None


class StoreError(RuntimeError):
    """Database failure with a message safe to print (no connection secrets)."""


DB_ERRORS = (sqlite3.Error,) + ((psycopg.Error,) if psycopg else ())


def now():
    return datetime.now(timezone.utc).isoformat()


def encode(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False)


def content(row):
    result = {key: row.get(key) for key in
              ("description", "date_filed", "time_filed", "entry_number")}
    docs = row.get("recap_documents", [])
    if not isinstance(docs, list) or any(not isinstance(d, dict) for d in docs):
        raise ValueError("Invalid recap_documents")
    result["documents"] = sorted(
        [{key: d.get(key) for key in ("id", "description", "document_number",
          "attachment_number", "is_available", "filepath_local", "filepath_ia",
          "plain_text", "sha1")} for d in docs], key=encode)
    return encode(result)


class Store:
    def __init__(self, path=":memory:", *, database_url=None):
        self.backend = "postgres" if database_url else "sqlite"
        self.conn = None
        if database_url and not database_url.startswith(("postgresql://", "postgres://")):
            raise StoreError("DATABASE_URL must be a PostgreSQL connection URL")
        if database_url and psycopg is None:
            raise StoreError("PostgreSQL requires psycopg; install requirements.txt")
        try:
            if self.backend == "postgres":
                self.conn = psycopg.connect(database_url, autocommit=True,
                                            row_factory=dict_row, connect_timeout=10)
            else:
                self.conn = sqlite3.connect(path)
                self.conn.row_factory = sqlite3.Row
                self.conn.execute("PRAGMA foreign_keys=ON")
            self._initialize()
        except (StoreError,) + DB_ERRORS:
            if self.conn is not None:
                self.conn.close()
            raise StoreError("Database initialization failed; check configuration and access") from None

    def _initialize(self):
        schema = """
        CREATE TABLE IF NOT EXISTS dockets (
            id INTEGER PRIMARY KEY, baseline_at TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS entries (
            docket_id INTEGER NOT NULL, id INTEGER NOT NULL,
            raw_json TEXT NOT NULL, content_json TEXT NOT NULL,
            PRIMARY KEY (docket_id, id));
        CREATE TABLE IF NOT EXISTS runs (
            id INTEGER PRIMARY KEY, docket_id INTEGER NOT NULL,
            source TEXT NOT NULL, started_at TEXT NOT NULL, finished_at TEXT,
            status TEXT NOT NULL, fetched INTEGER, added INTEGER,
            modified INTEGER, missing INTEGER, error TEXT);
        CREATE TABLE IF NOT EXISTS changes (
            id INTEGER PRIMARY KEY, run_id INTEGER NOT NULL REFERENCES runs(id),
            docket_id INTEGER NOT NULL, entry_id INTEGER NOT NULL,
            kind TEXT NOT NULL, before_json TEXT, after_json TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS email_outbox (
            key TEXT PRIMARY KEY, docket_id INTEGER, recipient TEXT, subject TEXT, body TEXT,
            message_id TEXT, status TEXT, created_at TEXT, finished_at TEXT, error TEXT);
        """
        if self.backend == "postgres":
            schema = schema.replace("INTEGER", "BIGINT")
            for table in ("runs", "changes"):
                schema = schema.replace(
                    f"{table} (\n            id BIGINT PRIMARY KEY",
                    f"{table} (\n            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        with self.transaction():
            for statement in schema.split(";"):
                if statement.strip():
                    self.execute(statement)

    def execute(self, sql, parameters=()):
        # Internal SQL uses ? placeholders, never literal '?' or PostgreSQL JSON operators.
        # Values always remain separate bound parameters.
        if self.backend == "postgres":
            sql = sql.replace("?", "%s")
        try:
            return self.conn.execute(sql, parameters)
        except DB_ERRORS:
            raise StoreError("Database operation failed") from None

    @contextmanager
    def transaction(self):
        try:
            if self.backend == "postgres":
                with self.conn.transaction():
                    yield
            else:
                # Acquire the write lock before reading the snapshot to avoid stale writes.
                self.conn.execute("BEGIN IMMEDIATE")
                with self.conn:
                    yield
        except DB_ERRORS:
            raise StoreError("Database transaction failed") from None

    def close(self):
        self.conn.close()

    def initialized(self, docket_id):
        return self.execute("SELECT 1 FROM dockets WHERE id=?", (docket_id,)).fetchone() is not None

    def start(self, docket_id, source="api"):
        with self.transaction():
            return self.execute(
                "INSERT INTO runs(docket_id,source,started_at,status) VALUES(?,?,?, 'running') RETURNING id",
                (docket_id, source, now())).fetchone()["id"]

    def fail(self, run_id, error):
        with self.transaction():
            self.execute("UPDATE runs SET status='failed', finished_at=?, error=? WHERE id=? AND status='running'",
                              (now(), error, run_id))

    def apply(self, run_id, rows):
        if not isinstance(rows, list):
            raise ValueError("Snapshot must be a list")
        with self.transaction():
            run = self.execute("SELECT * FROM runs WHERE id=?", (run_id,)).fetchone()
            if not run or run["status"] != "running":
                raise ValueError("Run is not active")
            docket_id = run["docket_id"]
            if self.backend == "postgres":
                # Serialize snapshot writes for this docket, including first baseline.
                self.execute("SELECT pg_advisory_xact_lock(?)", (docket_id,))
                run = self.execute("SELECT * FROM runs WHERE id=? FOR UPDATE", (run_id,)).fetchone()
                if run["status"] != "running":
                    raise ValueError("Run is not active")
            incoming = {}
            for row in rows:
                if not isinstance(row, dict) or type(row.get("id")) is not int or row["id"] <= 0:
                    raise ValueError("Every entry needs a positive integer ID")
                if row.get("docket") != f"https://www.courtlistener.com/api/rest/v4/dockets/{docket_id}/":
                    raise ValueError("Entry belongs to another docket or has no docket reference")
                if not isinstance(row.get("description"), str):
                    raise ValueError("Entry description must be a string")
                raw, signature = encode(row), content(row)
                if row["id"] in incoming and incoming[row["id"]] != (raw, signature):
                    raise ValueError("Conflicting duplicate entry IDs")
                incoming[row["id"]] = (raw, signature)
            previous = {r["id"]: r for r in self.execute(
                "SELECT * FROM entries WHERE docket_id=?", (docket_id,))}
            baseline = not self.initialized(docket_id)
            if baseline and not incoming:
                raise ValueError("Cannot establish a baseline from an empty snapshot")
            added = modified = 0
            missing = len(set(previous) - set(incoming))
            for entry_id, (raw, signature) in incoming.items():
                old = previous.get(entry_id)
                kind = "added" if old is None else "modified" if old["content_json"] != signature else None
                if kind and not baseline:
                    added += kind == "added"
                    modified += kind == "modified"
                    self.execute("INSERT INTO changes(run_id,docket_id,entry_id,kind,before_json,after_json) VALUES(?,?,?,?,?,?)",
                        (run_id, docket_id, entry_id, kind, old["raw_json"] if old else None, raw))
                self.execute("INSERT INTO entries VALUES(?,?,?,?) ON CONFLICT(docket_id,id) DO UPDATE SET raw_json=excluded.raw_json,content_json=excluded.content_json",
                                  (docket_id, entry_id, raw, signature))
            if baseline:
                self.execute("INSERT INTO dockets VALUES(?,?)", (docket_id, now()))
            self.execute("UPDATE runs SET status='success',finished_at=?,fetched=?,added=?,modified=?,missing=? WHERE id=?",
                              (now(), len(incoming), added, modified, missing, run_id))
        return dict(baseline=baseline, fetched=len(incoming), added=added, modified=modified, missing=missing)

    def list_changes(self, docket_id):
        return self.execute("SELECT id,after_json FROM changes WHERE docket_id=? ORDER BY id",
                            (docket_id,)).fetchall()

    def claim_email(self, key, docket_id, recipient, subject, body, message_id):
        with self.transaction():
            row = self.execute(
                "INSERT INTO email_outbox VALUES(?,?,?,?,?,?, 'sending', ?,NULL,NULL) "
                "ON CONFLICT(key) DO NOTHING RETURNING key",
                (key, docket_id, recipient, subject, body, message_id, now())).fetchone()
        return row is not None

    def email_status(self, key):
        return self.execute("SELECT status FROM email_outbox WHERE key=?", (key,)).fetchone()["status"]

    def finish_email(self, key, status, error=None):
        with self.transaction():
            self.execute("UPDATE email_outbox SET status=?,finished_at=?,error=? WHERE key=?",
                         (status, now(), error, key))
