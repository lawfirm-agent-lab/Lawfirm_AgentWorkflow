"""Offline backend tests; no environment file, service or real credentials used."""
from contextlib import contextmanager
from pathlib import Path
import tempfile
import unittest
from unittest.mock import MagicMock, patch

from src.store import db
from src.store.db import Store, StoreError
from src.notify.email import deliver


class BackendTests(unittest.TestCase):
    def test_reopen_preserves_snapshot_and_email_dedup(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'test.db'
            cfg = {'EMAIL_FROM': 'a@example.com', 'EMAIL_TO': 'b@example.com'}
            sent = []
            row = {'id': 1, 'docket': 'https://www.courtlistener.com/api/rest/v4/dockets/1/',
                   'description': 'ORDER', 'recap_documents': []}
            store = Store(path)
            store.apply(store.start(1), [row])
            deliver(store, 1, ('Subject', 'Body'), 'change:1', cfg, sent.append)
            store.close()
            store = Store(path)
            try:
                self.assertTrue(store.initialized(1))
                self.assertFalse(store.apply(store.start(1), [row])['baseline'])
                deliver(store, 1, ('Subject', 'Body'), 'change:1', cfg, sent.append)
                self.assertEqual(len(sent), 1)
            finally:
                store.close()

    def test_transaction_rolls_back_partial_write(self):
        store = Store(':memory:')
        self.addCleanup(store.close)
        with self.assertRaises(StoreError):
            with store.transaction():
                store.execute('INSERT INTO dockets VALUES(?,?)', (1, 'today'))
                store.execute('INSERT INTO missing_table VALUES(?)', (1,))
        self.assertFalse(store.initialized(1))
        # Failed transaction must not poison future operations.
        with store.transaction():
            store.execute('INSERT INTO dockets VALUES(?,?)', (2, 'today'))
        self.assertTrue(store.initialized(2))

    def test_invalid_url_never_creates_sqlite_file(self):
        with self.assertRaisesRegex(StoreError, 'PostgreSQL connection URL'):
            Store(database_url='https://user:private@example.com/db')

    def test_missing_driver(self):
        with patch.object(db, 'psycopg', None):
            with self.assertRaisesRegex(StoreError, 'requires psycopg'):
                Store(database_url='postgresql://test:test@localhost/test')

    def test_postgres_adapter_schema_transactions_and_parameters(self):
        driver = MagicMock()
        connection = driver.connect.return_value
        with patch.object(db, 'psycopg', driver), patch.object(db, 'dict_row', object(), create=True):
            store = Store(database_url='postgresql://test:test@localhost/test')
            self.addCleanup(store.close)
            ddl = '\n'.join(c.args[0] for c in connection.execute.call_args_list)
            self.assertEqual(ddl.count('GENERATED BY DEFAULT AS IDENTITY'), 2)
            self.assertIn('run_id BIGINT', ddl)
            self.assertIn('email_outbox', ddl)
            connection.execute.return_value.fetchone.return_value = {'id': 7}
            self.assertEqual(store.start(1), 7)
            sql, params = connection.execute.call_args.args
            self.assertIn('RETURNING id', sql)
            self.assertIn('%s', sql)
            self.assertNotIn('?', sql)
            self.assertEqual(params[0], 1)
            self.assertTrue(driver.connect.call_args.kwargs['autocommit'])
            self.assertEqual(connection.transaction.call_count, 2)
            connection.__enter__.assert_not_called()
            connection.close.assert_not_called()

    def test_connection_errors_hide_credentials(self):
        driver = MagicMock()
        driver.connect.side_effect = db.sqlite3.OperationalError('password=private host=secret')
        with patch.object(db, 'psycopg', driver), patch.object(db, 'dict_row', object(), create=True):
            with self.assertRaises(StoreError) as error:
                Store(database_url='postgresql://user:private@secret/test')
            self.assertNotIn('private', str(error.exception))
            self.assertNotIn('secret', str(error.exception))

    def test_failed_apply_rolls_back_already_written_entries(self):
        store = Store(':memory:')
        self.addCleanup(store.close)
        row = lambda i: {'id': i, 'docket': 'https://www.courtlistener.com/api/rest/v4/dockets/1/',
                         'description': 'ORDER', 'recap_documents': []}
        store.apply(store.start(1), [row(1)])
        run = store.start(1)
        execute = store.execute
        def fail_second(sql, params=()):
            if sql.startswith('INSERT INTO entries') and params[1] == 3:
                raise StoreError('injected write failure')
            return execute(sql, params)
        with patch.object(store, 'execute', side_effect=fail_second):
            with self.assertRaises(StoreError):
                store.apply(run, [row(1), row(2), row(3)])
        self.assertEqual(len(store.list_changes(1)), 0)
        self.assertEqual(store.execute('SELECT COUNT(*) AS n FROM entries').fetchone()['n'], 1)
        store.fail(run, 'test failure')
        self.assertEqual(store.apply(store.start(1), [row(1)])['added'], 0)


class MainBackendTests(unittest.TestCase):
    def test_main_passes_database_url_without_loading_private_env(self):
        import os
        from src import main as entrypoint
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / 'config.yaml').write_text('dockets: [1]\n')
            with patch.object(entrypoint, 'ROOT', root), \
                 patch.object(entrypoint, 'load_dotenv') as dotenv, \
                 patch.object(entrypoint, 'Store') as factory, \
                 patch('sys.argv', ['main', '--import-baseline']), \
                 patch.dict(os.environ, {'DATABASE_URL': 'postgresql://test:test@localhost/test'}, clear=True):
                factory.return_value.initialized.return_value = True
                self.assertEqual(entrypoint.main(), 0)
                factory.assert_called_once_with(root / 'data/docket.db', database_url='postgresql://test:test@localhost/test')
                factory.return_value.close.assert_called_once()
                dotenv.assert_called_once_with(root / '.env')

    def test_main_default_keeps_sqlite(self):
        import os
        from src import main as entrypoint
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / 'config.yaml').write_text('dockets: [1]\n')
            with patch.object(entrypoint, 'ROOT', root), \
                 patch.object(entrypoint, 'load_dotenv'), \
                 patch.object(entrypoint, 'Store') as factory, \
                 patch('sys.argv', ['main', '--import-baseline']), \
                 patch.dict(os.environ, {}, clear=True):
                factory.return_value.initialized.return_value = True
                self.assertEqual(entrypoint.main(), 0)
                factory.assert_called_once_with(root / 'data/docket.db', database_url=None)
